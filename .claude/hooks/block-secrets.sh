#!/usr/bin/env bash
# PreToolUse-хук Claude Code для Bash: защита от случайного чтения секретов агентом.
#
# Deny-правила на Read не мешают агенту сделать `cat .env` или `python -c open(...)`,
# поэтому хук смотрит на саму команду. Это защита от случайности, а не от целенаправленного
# обхода: строку можно собрать так, что регулярное выражение её не узнает (base64, переменные).
# Настоящий барьер — секретов нет в рабочей копии агента, а песочница не даёт выйти за неё.
#
# Вход — JSON вызова инструмента на stdin. Код 2 — отказ с сообщением агенту.
set -uo pipefail

deny() {
  echo "Отклонено хуком: $1. Нужен ключ или доступ — попроси человека." >&2
  exit 2
}

# Без jq команду не разобрать. Лучше отказать, чем пропустить вслепую.
command -v jq >/dev/null 2>&1 || deny "не найден jq, команду проверить нельзя"

raw="$(jq -r '.tool_input.command // ""' 2>/dev/null)" || deny "не удалось прочитать вызов"

# Нормализация: убрать кавычки, обратные слэши и glob-скобки, которыми разрывают имя
# файла (.e""nv, .e\nv, .[e]nv), привести к нижнему регистру.
cmd="$(printf '%s' "$raw" | tr -d "\"'\\\\[]" | tr '[:upper:]' '[:lower:]')"

# Учебный .env.example разрешён, но только он: вырезаем его и проверяем остаток,
# чтобы `cat .env.example .env` не проходил под прикрытием разрешённого файла.
rest="${cmd//.env.example/}"

patterns=(
  '(^|[^a-z0-9_.-])\.env([^a-z0-9_]|$)'   # .env в любом месте команды
  '\.env\.[a-z0-9_]+'                       # .env.local, .env.production и т. п.
  '\.en[?*]'                                # маска вместо имени: .en?, .en*
  '(^|[^a-z0-9_.-])secrets?/'               # каталог secrets/
  '[a-z0-9_-]\.(pem|key|p12|pfx)\b'         # файлы ключей (но не `jq .key`)
  'id_(rsa|ed25519|ecdsa|dsa)'              # ssh-ключи
  'credentials\.json|\.netrc|\.pgpass'      # частые файлы с учётными данными
  '\.ssh/|\.aws/|\.config/gcloud'           # каталоги с ключами
)

for re in "${patterns[@]}"; do
  printf '%s\n' "$rest" | grep -qE "$re"
  case $? in
    0) deny "команда обращается к секретам" ;;
    1) ;;  # совпадения нет
    *) deny "ошибка проверки команды" ;;  # сбой grep — не повод пропускать
  esac
done
exit 0
